import streamlit as st


def show():
    st.title("🧠 终局思维模型")
    st.caption("用长期视角指导投资决策")
    
    st.divider()
  
    # ==================== 核心理念详细说明 ====================
    st.header("🧠 终局思维：核心理念")
    st.markdown("""
    **终局思维模型**是一套以长期价值为导向的股票分析框架，其核心逻辑是：**以当前时间为起点，设定三年后为“终局时刻”，通过预测公司在终局时刻的市值，反推当前股价是否具备足够的安全边际和赔率，从而判断标的的长期吸引力。**
    
    ### 💡 核心思想
    
    > **“买股票就是买公司，买公司就是买其未来自由现金流的折现。”**
    
    该模型基于巴菲特的长期价值投资理念，结合中国 A 股市场的特点进行了本土化改良。与传统分析侧重短期业绩波动不同，终局思维模型**强迫投资者从“终局确定性”出发**——即三年后这家公司大概率值多少钱，而非下个季度业绩是否超预期。
    """)
    
    # ==================== 核心理念拆解 ====================
    st.header("📐 核心理念拆解")
    
    col1, col2 = st.columns(2)
    
    with col1:
        st.subheader("1. 以终为始，反推当下价值")
        st.markdown("""
        模型不预测股价涨跌，而是通过 **终局市值→折现→修正→对比当前市值** 的链条，计算出 **真实赔率** 和 **动态安全边际**。只有当赔率≥1且安全边际≥1时，估值才具备吸引力。
        """)
        
        st.subheader("2. 三情景概率加权，校准主观判断")
        st.markdown("""
        模型要求设定 **乐观、中性、悲观** 三种情景，并明确各情景的发生概率。悲观概率必须≥25%，乐观概率必须≤25%，以此强制投资者正视下行风险，避免过度乐观。
        """)
    
    with col2:
        st.subheader("3. 内部人信号修正估值")
        st.markdown("""
        将大股东减持、回购、限售解禁等资金面信号量化为修正系数（0.80~1.10），对折现后终局市值进行堆叠修正，使估值更贴近真实价值。
        """)
        
        st.subheader("4. 安全边际差异化")
        st.markdown("""
        根据公司的确定性等级（极高→极低），设定差异化的安全边际系数（85%→0%）。越确定的公司，安全边际要求越低；越不确定的公司，安全边际要求越高。
        """)
    
    st.divider()
    
    # ==================== 适用场景 ====================
    st.header("🎯 适用场景")
    st.markdown("""
    ✅ **适合使用终局思维模型的情况：**
    - 寻找**长期持有**的价值标的
    - 分析**商业模式清晰**的成熟企业
    - 制定**3-5年**的投资规划
    - 评估**白马股**、**蓝筹股**的长期价值
    
    ⚠️ **不适合使用的情况：**
    - 短期投机、波段交易
    - 概念炒作、题材股
    - 周期股（强周期性行业）
    - 亏损或初创企业
    """)
    
    st.divider()
    
    # ==================== 免责声明 ====================
    with st.expander("📋 免责声明"):
        st.markdown("""
        ⚠️ **重要声明**
        
        终局思维模型是一种分析工具，旨在帮助投资者从长期视角评估公司价值。其分析结果基于公开信息和历史数据，**不构成任何投资建议**。
        
        股票市场存在风险，投资需谨慎。本模型的分析结果仅供参考，**不应作为投资决策的唯一依据**。投资者应结合自身风险承受能力、投资目标和市场情况，做出独立的投资判断。
        
        模型的分析者不对任何投资损失承担任何责任。
        """)
    
    st.divider()
    st.caption("📌 该模型持续迭代中，当前版本：V2.7 | 数据更新日期：2026年8月")